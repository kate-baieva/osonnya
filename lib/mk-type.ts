// Колонка «MK Type» в аркуші «Certificate Orders» — строгий випадний список
// рівно з двох значень: group і individual. Записати туди через API можна
// будь-що (валідація зупиняє лише ручне введення), але тоді клітинка
// лишається з червоною позначкою, а фільтри й зведені таблиці за нею
// перестають сходитись. Тому все, що йде в цю колонку, проходить тут.
//
// Парний МК для таблиці — теж individual: окремого значення для нього в
// списку немає. Людиночитну назву («Парний МК») формуємо окремо, для листів.

export const MK_TYPE_GROUP = 'group'
export const MK_TYPE_INDIVIDUAL = 'individual'

// Приймає назву формату з аркуша «Prices» («Груповий МК», «Парний МК»,
// «Індивідуальний МК на 4 людини») або вже готове значення списку.
export function sheetMkType(value: string): string {
  const text = String(value ?? '').toLowerCase()
  // 'груповий' — та сама ознака, за якою груповий формат відрізняють
  // решта коду: parsePricesSheet і форма видачі сертифіката
  return text.includes('груповий') || text === MK_TYPE_GROUP
    ? MK_TYPE_GROUP
    : MK_TYPE_INDIVIDUAL
}
